package me.ayydxn.niagara.codegen.ffm;

import me.ayydxn.niagara.core.backend.NativeBackendType;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Collectors;

import static me.ayydxn.niagara.codegen.NativeInterfaceModel.*;

public final class FFMNativeBindingsEmitter
{
    private static final String GENERATED_BY = "// GENERATED by NiagaraNativeBindingsGenerator";
    private static final String SUPPORT_CLASS = "me.ayydxn.niagara.ffm.FFMNativeSupport";

    private final String javaPackage;

    public FFMNativeBindingsEmitter(String javaPackage)
    {
        this.javaPackage = javaPackage;
    }

    public Map<String, String> javaFiles(List<Contract> contracts)
    {
        Map<String, String> files = new TreeMap<>();

        for (Contract contract : sorted(contracts))
            files.put((this.javaPackage + "." + javaSimpleName(contract)).replace('.', '/') + ".java", javaSource(contract));

        return files;
    }

    private static List<Contract> sorted(List<Contract> contracts)
    {
        return contracts.stream().sorted(Comparator.comparing(Contract::name)).toList();
    }

    private String javaSource(Contract contract)
    {
        List<Function> generated = contract.functions().stream().filter(f -> !f.isCustom(NativeBackendType.FFM)).toList();
        boolean isAbstract = generated.size() != contract.functions().size();

        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append(GENERATED_BY).append(" from ").append(contract.name()).append(". DO NOT EDIT.\n");
        stringBuilder.append("// Generated on ").append(LocalDateTime.now()).append(".\n");
        stringBuilder.append("package ").append(this.javaPackage).append(";\n\n");
        stringBuilder.append("import ").append(contract.type().getName()).append(";\n");

        if (!generated.isEmpty())
        {
            stringBuilder.append("import ").append(SUPPORT_CLASS).append(";\n\n");

            if (generated.stream().anyMatch(f -> f.params().stream().anyMatch(p -> p.type().isNativeString())))
                stringBuilder.append("import java.lang.foreign.Arena;\n");

            stringBuilder.append("import java.lang.foreign.FunctionDescriptor;\n");

            if (generated.stream().anyMatch(FFMNativeBindingsEmitter::usesMemorySegment))
                stringBuilder.append("import java.lang.foreign.MemorySegment;\n");

            stringBuilder.append("import java.lang.foreign.ValueLayout;\n");
            stringBuilder.append("import java.lang.invoke.MethodHandle;\n");
        }

        stringBuilder.append('\n');

        if (isAbstract)
        {
            stringBuilder.append("/**\n * Everything the generator can do for ").append(contract.name()).append(". The functions that are handwritten for FFM are left to ")
                    .append("FFM").append(contract.name()).append(", which extends this class.\n */\n");
            stringBuilder.append("public abstract class ");
        }
        else
        {
            stringBuilder.append("public final class ");
        }

        stringBuilder.append(javaSimpleName(contract)).append(" implements ").append(contract.name()).append("\n{\n");

        List<String> members = new ArrayList<>();
        for (Function function : generated)
            members.add(handleField(function));

        for (Function function : generated)
            members.add(method(function));

        stringBuilder.append(String.join("\n", members));
        return stringBuilder.append("}\n").toString();
    }

    private static String handleField(Function function)
    {
        String layouts = function.params().stream().map(p -> layout(p.type())).collect(Collectors.joining(", "));

        String descriptor;
        if (function.returnType().kind() == Kind.VOID)
            descriptor = "FunctionDescriptor.ofVoid(" + layouts + ")";
        else
            descriptor = "FunctionDescriptor.of(" + layout(function.returnType()) + (layouts.isEmpty() ? "" : ", " + layouts) + ")";

        return "    private static final MethodHandle " + function.cName() + " = FFMNativeSupport.downcall(\"" + function.cName() + "\",\n            " + descriptor + ");\n";
    }

    private static String method(Function function)
    {
        boolean usesArena = function.params().stream().anyMatch(p -> p.type().isNativeString());

        String args = function.params().stream().map(FFMNativeBindingsEmitter::argument).collect(Collectors.joining(", "));
        String invocation = function.cName() + ".invokeExact(" + args + ")";
        Type returnType = function.returnType();

        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append("    @Override\n    public ").append(returnType.kind().javaType).append(' ').append(function.javaName())
                .append('(').append(javaParams(function)).append(")\n    {\n");
        stringBuilder.append(usesArena ? "        try (Arena nativeArena = Arena.ofConfined())\n" : "        try\n").append("        {\n");

        if (returnType.kind() == Kind.VOID)
        {
            stringBuilder.append("            ").append(invocation).append(";\n");
        }
        else if (returnType.pointerType() != null)
        {
            stringBuilder.append("            return ((MemorySegment) ").append(invocation).append(").address();\n");
        }
        else if (returnType.isNativeString())
        {
            stringBuilder.append("            return FFMNativeSupport.readNativeString((MemorySegment) ").append(invocation).append(");\n");
        }
        else if (returnType.ulString() && returnType.ownedULString())
        {
            stringBuilder.append("            MemorySegment nativeResult = (MemorySegment) ").append(invocation).append(";\n");
            stringBuilder.append("            String nativeString = FFMNativeSupport.readULString(nativeResult);\n");
            stringBuilder.append("            FFMNativeSupport.destroyULString(nativeResult);\n\n");
            stringBuilder.append("            return nativeString;\n");
        }
        else if (returnType.ulString())
        {
            stringBuilder.append("            return FFMNativeSupport.readULString((MemorySegment) ").append(invocation).append(");\n");
        }
        else
        {
            stringBuilder.append("            return (").append(returnType.kind().javaType).append(") ").append(invocation).append(";\n");
        }

        return stringBuilder.append("        }\n        catch (Throwable nativeThrowable)\n        {\n            throw FFMNativeSupport.failure(\"")
                .append(function.cName()).append("\", nativeThrowable);\n        }\n    }\n").toString();
    }

    private static String argument(Param parameter)
    {
        Type type = parameter.type();

        if (type.pointerType() != null)
            return "MemorySegment.ofAddress(" + parameter.javaName() + ")";

        // invokeExact matches the exact static type of every argument, and a bare conditional counts as an Object there.
        if (type.isNativeString())
            return "(MemorySegment) (" + parameter.javaName() + " == null ? MemorySegment.NULL : nativeArena.allocateFrom(" + parameter.javaName() + "))";

        return parameter.javaName();
    }

    private static boolean isAddress(Type type)
    {
        return type.pointerType() != null || type.isNativeString() || type.ulString();
    }

    private static boolean usesMemorySegment(Function function)
    {
        return isAddress(function.returnType()) || function.params().stream().anyMatch(p -> isAddress(p.type()));
    }

    private static String layout(Type type)
    {
        if (isAddress(type))
            return "ValueLayout.ADDRESS";

        return switch (type.kind())
        {
            case INT -> "ValueLayout.JAVA_INT";
            case DOUBLE -> "ValueLayout.JAVA_DOUBLE";
            case LONG -> "ValueLayout.JAVA_LONG";
            case BOOLEAN -> "ValueLayout.JAVA_BOOLEAN";
            case VOID, STRING -> throw new IllegalArgumentException("Can't pass a " + type.kind().javaType + " through FFM without an annotation saying what it is");
        };
    }

    private static String javaParams(Function function)
    {
        return function.params().stream().map(p -> p.type().kind().javaType + " " + p.javaName()).collect(Collectors.joining(", "));
    }

    private static String javaSimpleName(Contract contract)
    {
        boolean isAbstract = contract.functions().stream().anyMatch(f -> f.isCustom(NativeBackendType.FFM));

        return (isAbstract ? "AbstractFFM" : "FFM") + contract.name();
    }
}

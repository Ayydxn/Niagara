package me.ayydxn.niagara.codegen.jni;

import me.ayydxn.niagara.core.backend.NativeBackendType;

import java.time.LocalDateTime;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Collectors;

import static me.ayydxn.niagara.codegen.NativeInterfaceModel.*;

public final class JNINativeBindingsEmitter
{
    private static final String CPP_DIRECTORY = "ultralight";
    private static final String GENERATED_BY = "// GENERATED by NiagaraNativeBindingsGenerator";

    private final String javaPackage;

    public JNINativeBindingsEmitter(String javaPackage)
    {
        this.javaPackage = javaPackage;
    }

    public Map<String, String> javaFiles(List<Contract> contracts)
    {
        Map<String, String> files = new TreeMap<>();

        for (Contract contract : sorted(contracts))
            files.put((javaPackage + "." + javaSimpleName(contract)).replace('.', '/') + ".java", javaSource(contract));

        return files;
    }

    public Map<String, String> cppFiles(List<Contract> contracts)
    {
        Map<String, String> files = new TreeMap<>();
        List<Contract> sorted = sorted(contracts);

        for (Contract contract : sorted)
        {
            files.put(CPP_DIRECTORY + "/" + contract.baseName() + ".h", cppHeader(contract));
            files.put(CPP_DIRECTORY + "/" + contract.baseName() + ".cpp", cppSource(contract));
        }

        files.put("GeneratedNativeInterfaces.h", registryHeader(sorted));
        return files;
    }

    private static List<Contract> sorted(List<Contract> contracts)
    {
        return contracts.stream().sorted(Comparator.comparing(Contract::name)).toList();
    }

    private String javaSource(Contract contract)
    {
        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append(GENERATED_BY).append(" from ").append(contract.name()).append(". DO NOT EDIT.\n");
        stringBuilder.append("// Generated on ").append(LocalDateTime.now()).append(".\n");
        stringBuilder.append("package ").append(javaPackage).append(";\n\n");
        stringBuilder.append("import ").append(contract.type().getName()).append(";\n\n");
        stringBuilder.append("public final class ").append(javaSimpleName(contract)).append(" implements ").append(contract.name()).append("\n{\n");

        for (Function function : contract.functions())
        {
            String args = function.params().stream().map(Param::javaName).collect(Collectors.joining(", "));
            String call = "NativeMethods." + nativeName(function) + "(" + args + ");";

            stringBuilder.append("    @Override\n    public ").append(function.returnType().kind().javaType).append(' ').append(function.javaName())
                    .append('(').append(javaParams(function)).append(")\n    {\n        ")
                    .append(function.returnType().kind() == Kind.VOID ? "" : "return ").append(call).append("\n    }\n\n");
        }

        stringBuilder.append("    private static final class NativeMethods\n    {\n");
        for (Function f : contract.functions())
        {
            stringBuilder.append("        private static native ").append(f.returnType().kind().javaType).append(' ')
                    .append(nativeName(f)).append('(').append(javaParams(f)).append(");\n\n");
        }

        stringBuilder.setLength(stringBuilder.length() - 1);
        return stringBuilder.append("    }\n}\n").toString();
    }

    private static String javaParams(Function f)
    {
        return f.params().stream().map(p -> p.type().kind().javaType + " " + p.javaName()).collect(Collectors.joining(", "));
    }

    private static String cppHeader(Contract contract)
    {
        return """
                // GENERATED by NiagaraNativeBindingsGenerator from %1$s. DO NOT EDIT.
                // Generated on %2$s.
                #pragma once

                #include "core/NativeInterface.h"

                class %3$s : public INativeInterface
                {
                public:
                    ~%3$s() override = default;

                    const char* GetClassName() const override;
                    const std::vector<JNINativeMethod> GetNativeMethods() const override;
                };
                """.formatted(contract.name(), LocalDateTime.now(), cppClass(contract));
    }

    private String cppSource(Contract contract)
    {
        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append(GENERATED_BY).append(" from ").append(contract.name()).append(". DO NOT EDIT.\n");
        stringBuilder.append("// Generated on ").append(LocalDateTime.now()).append(".\n");
        stringBuilder.append("#include \"").append(contract.baseName()).append(".h\"\n#include \"utils/JNIUtils.h\"\n\n");
        for (String header : contract.headers())
            stringBuilder.append("#include <").append(header).append(">\n");
        stringBuilder.append('\n');

        List<Function> custom = contract.functions().stream().filter(f -> f.isCustom(NativeBackendType.JNI)).toList();
        for (Function f : custom)
            stringBuilder.append(cppSignature(f)).append(";\n");
        if (!custom.isEmpty())
            stringBuilder.append('\n');

        stringBuilder.append("namespace\n{\n");
        List<Function> generated = contract.functions().stream().filter(f -> !f.isCustom(NativeBackendType.JNI)).toList();
        for (int i = 0; i < generated.size(); i++)
        {
            stringBuilder.append(cppFunction(contract, generated.get(i)));
            stringBuilder.append(i + 1 < generated.size() ? "\n" : "");
        }
        stringBuilder.append("}\n\n");

        stringBuilder.append("const char* ").append(cppClass(contract)).append("::GetClassName() const\n{\n    return \"")
                .append(jniInternalName(contract)).append("\";\n}\n\n");

        stringBuilder.append("const std::vector<JNINativeMethod> ").append(cppClass(contract)).append("::GetNativeMethods() const\n{\n    return\n    {\n");
        for (int i = 0; i < contract.functions().size(); i++)
        {
            Function f = contract.functions().get(i);
            stringBuilder.append("        CJNIUtils::MakeNativeMethod(\"%s\", \"%s\", %s)%s\n"
                    .formatted(nativeName(f), signature(f), cppName(f), i + 1 < contract.functions().size() ? "," : ""));
        }
        stringBuilder.append("    };\n}\n");

        return stringBuilder.toString();
    }

    private static String cppSignature(Function function)
    {
        boolean usesEnvironment = function.isCustom(NativeBackendType.JNI)
                || function.returnType().kind() == Kind.STRING
                || function.params().stream().anyMatch(p -> p.type().kind() == Kind.STRING);

        String params = function.params().stream()
                .map(p -> jniType(p.type().kind()) + " " + cppName(p))
                .collect(Collectors.joining(", "));

        return "%s JNICALL %s(JNIEnv*%s, jclass%s)".formatted(jniType(function.returnType().kind()), cppName(function),
                usesEnvironment ? " Environment" : "", params.isEmpty() ? "" : ", " + params);
    }

    private String cppFunction(Contract contract, Function function)
    {
        for (Param parameter : function.params())
        {
            if (parameter.type().kind() == Kind.STRING)
                throw new IllegalArgumentException("The JNI backend can't generate String parameters (" + parameter.javaName() + " on " + contract.name() + "." + function.javaName()
                        + "). Add NativeBackendType.JNI to custom and write the C++ body by hand.");
        }

        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append("    /*\n     * Class:     ").append(bannerName(contract)).append("\n")
                .append("     * Method:    ").append(nativeName(function)).append("\n")
                .append("     * Signature: ").append(signature(function)).append("\n     */\n");
        stringBuilder.append("    ").append(cppSignature(function)).append("\n    {\n");

        String arguments = function.params().stream().map(JNINativeBindingsEmitter::cppArgument).collect(Collectors.joining(", "));
        String call = function.cName() + "(" + arguments + ")";
        Type returnType = function.returnType();

        if (returnType.kind() == Kind.VOID)
            stringBuilder.append("        ").append(call).append(";\n");
        else if (returnType.pointerType() != null)
            stringBuilder.append("        return reinterpret_cast<jlong>(").append(call).append(");\n");
        else if (returnType.isNativeString())
            stringBuilder.append("        return Environment->NewStringUTF(").append(call).append(");\n");
        else if (returnType.ulString())
        {
            stringBuilder.append("        const ULString Result = ").append(call).append(";\n");
            stringBuilder.append("        if (!Result)\n            return nullptr;\n\n");
            stringBuilder.append("        const jstring JavaString = CJNIUtils::ToJavaString(Environment, Result);\n");
            if (returnType.ownedULString())
                stringBuilder.append("        ulDestroyString(Result);\n");
            stringBuilder.append("\n        return JavaString;\n");
        }
        else
            stringBuilder.append("        return static_cast<").append(jniType(returnType.kind())).append(">(").append(call).append(");\n");

        return stringBuilder.append("    }\n").toString();
    }

    private static String cppArgument(Param parameter)
    {
        Type type = parameter.type();

        if (type.pointerType() != null)
            return "reinterpret_cast<" + type.pointerType() + ">(" + cppName(parameter) + ")";
        if (type.nativeType() != null)
            return "static_cast<" + type.nativeType() + ">(" + cppName(parameter) + ")";
        if (type.kind() == Kind.BOOLEAN)
            return "static_cast<bool>(" + cppName(parameter) + ")";

        return cppName(parameter);
    }

    private static String registryHeader(List<Contract> contracts)
    {
        StringBuilder stringBuilder = new StringBuilder();

        stringBuilder.append(GENERATED_BY).append(". DO NOT EDIT.\n");
        stringBuilder.append("// Generated on ").append(LocalDateTime.now()).append(".\n");
        stringBuilder.append("#pragma once\n\n#include \"core/NativeInterfaceRegistry.h\"\n\n");

        for (Contract contract : contracts)
            stringBuilder.append("#include \"").append(CPP_DIRECTORY).append('/').append(contract.baseName()).append(".h\"\n");

        stringBuilder.append("\n#include <memory>\n\ninline void AddGeneratedNativeInterfaces(CNativeInterfaceRegistry& Registry)\n{\n");
        for (Contract contract : contracts)
            stringBuilder.append("    Registry.Add(std::make_shared<").append(cppClass(contract)).append(">());\n");

        return stringBuilder.append("}\n").toString();
    }

    private String javaSimpleName(Contract contract)
    {
        return "JNI" + contract.name();
    }

    private String jniInternalName(Contract contract)
    {
        return (javaPackage + "." + javaSimpleName(contract)).replace('.', '/') + "$NativeMethods";
    }

    private String bannerName(Contract contract)
    {
        return (javaPackage + "." + javaSimpleName(contract)).replace('.', '_') + "_NativeMethods";
    }

    private static String cppClass(Contract contract)
    {
        return "C" + contract.baseName();
    }

    private static String nativeName(Function function)
    {
        return "n" + function.cName();
    }

    private static String cppName(Function function)
    {
        if (!function.cName().startsWith("ul"))
            throw new IllegalArgumentException("Expected an Ultralight C function starting with \"ul\", got " + function.cName());

        return "UL" + function.cName().substring(2) + "_Native";
    }

    private static String cppName(Param parameter)
    {
        String pascal = Character.toUpperCase(parameter.javaName().charAt(0)) + parameter.javaName().substring(1);
        return parameter.type().kind() == Kind.BOOLEAN ? "b" + pascal : pascal;
    }

    private static String signature(Function function)
    {
        return "(" + function.params().stream().map(p -> getKindJNISignature(p.type().kind())).collect(Collectors.joining()) + ")" +
                getKindJNISignature(function.returnType().kind());
    }

    private static String jniType(Kind kind)
    {
        return switch (kind)
        {
            case VOID -> "void";
            case INT -> "jint";
            case DOUBLE -> "jdouble";
            case LONG -> "jlong";
            case BOOLEAN -> "jboolean";
            case STRING -> "jstring";
        };
    }

    private static String getKindJNISignature(Kind kind)
    {
        return switch (kind)
        {
            case VOID -> "V";
            case INT -> "I";
            case DOUBLE -> "D";
            case LONG -> "J";
            case BOOLEAN -> "Z";
            case STRING -> "Ljava/lang/String;";
        };
    }
}
